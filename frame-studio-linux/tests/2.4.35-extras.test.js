const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const main = fs.readFileSync(path.join(root, 'main.cjs'), 'utf8');
const preload = fs.readFileSync(path.join(root, 'preload.cjs'), 'utf8');
const customization = fs.readFileSync(path.join(root, 'customization.js'), 'utf8');
const { parseWhisperTranscript } = require(path.join(root, 'subtitle-transcript.cjs'));
assert.doesNotMatch(html, /id="addR6Rig"/);
assert.doesNotMatch(html, /id="importObjButton"/);
assert.match(html, /function renderModelAsset\(/, 'legacy model renderer remains available for old projects');
assert.match(html, /importação de objetos 3D foi removida/, 'new OBJ imports are intentionally disabled');
assert.match(html, /function parseObjModel\(/);
assert.match(html, /function buildR6Mesh\(/);
assert.match(html, /function renderModelAsset\(/);
assert.match(html, /id="generateSubtitles"/);
assert.match(html, /transcribeAudio\(\{path:source\.asset\.path/);
assert.match(main, /frame:transcribe-audio/);
assert.match(main, /whisper-cli/);
assert.match(main, /FFmpeg audio extraction/);
assert.match(preload, /transcribeAudio: \(payload\)/);
assert.match(html, /modelTexturePath/);
assert.match(html, /modelPoseKeyframes/);
assert.match(main, /parseWhisperTranscript\(raw\)/);
assert.match(customization, /function transitionBackgroundPalette\(/);
assert.match(customization, /--accent-fill.*generatedAccentGradient/);
const offsets = parseWhisperTranscript({ result: { language: 'en' }, transcription: [{ offsets: { from: 80, to: 1470 }, text: 'test' }] });
assert.equal(offsets.segments[0].start, 0.08);
assert.equal(offsets.segments[0].end, 1.47);
const timestamps = parseWhisperTranscript({ result: { language: 'pt' }, transcription: [{ timestamps: { from: '00:00:01.250', to: '00:00:02.000' }, text: 'Olá' }] });
assert.equal(timestamps.segments[0].start, 1.25);
assert.equal(timestamps.segments[0].end, 2);
assert.throws(() => parseWhisperTranscript({ result: { language: 'es' }, transcription: [{ offsets: { from: 0, to: 1 }, text: 'hola' }] }), /not supported/);
console.log('2.4.35 extras wiring and transcript timing tests passed');
