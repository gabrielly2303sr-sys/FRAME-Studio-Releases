"use strict";
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const renderer=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][0]?.[1]||'';
assert.equal(pkg.version,'2.4.44');
assert.match(html,/id="opacityrange"[^>]*data-prop="opacity"[^>]*type="range"/,'opacity slider is visible and bound to the clip property');
assert.match(html,/id="opacitynumber"[^>]*data-prop="opacity"[^>]*type="number"/,'opacity remains numerically editable');
assert.match(html,/data-key="opacity"/,'opacity supports keyframes');
assert.match(renderer,/if\(inp\.dataset\.prop==='opacity'\)/,'opacity controls synchronize while editing');
assert.match(html,/data-dock-panel="library"/);
assert.match(html,/data-dock-panel="viewer"/);
assert.match(html,/data-dock-panel="inspector"/);
assert.match(html,/data-dock-handle/);
assert.match(renderer,/function normalizeWorkspaceDockOrder\(value\)/);
assert.match(renderer,/function initWorkspaceDocking\(\)/);
assert.match(renderer,/function resetWorkspaceLayout\(\)/);
assert.match(renderer,/frame-workspace-layout/);
assert.match(html,/id="resetWorkspaceLayout"/);
assert.match(html,/id="previewfullscreen"/,'viewer exposes a fullscreen playback control');
assert.match(html,/id="exportformat"/,'export dialog exposes the output container');
assert.match(html,/id="exportmode"/,'export dialog exposes realtime and frame-accurate modes');
assert.match(renderer,/ph\.addEventListener\('pointerdown',beginPlayheadDrag\)/,'rebuilt playhead keeps its pointer-drag handler');
assert.doesNotMatch(renderer,/\$\('#playhead'\)\.addEventListener\('pointerdown',beginPlayheadDrag\)/,'playhead drag is not bound only to the initial DOM node');
assert.match(renderer,/function frameEffectFolder\(item\)/);
for(const folder of ['Blur & Distortion','Light & Glow','Color & Correction','Texture & Style','Motion & Camera']) assert.ok(renderer.includes(folder),`effect folder ${folder} exists`);
assert.match(renderer,/function renderEffectLibrary\(\)/);
const getFunction=(name)=>{const start=renderer.indexOf(`function ${name}(`);assert.ok(start>=0,`${name} exists`);const brace=renderer.indexOf('{',start);let depth=0,quote=null,escape=false;for(let i=brace;i<renderer.length;i++){const c=renderer[i];if(quote){if(escape)escape=false;else if(c==='\\')escape=true;else if(c===quote)quote=null}else{if(c==='"'||c==="'"||c==='`')quote=c;else if(c==='{')depth++;else if(c==='}'&&--depth===0)return renderer.slice(start,i+1)}}throw new Error(`function end missing: ${name}`)};
const contextTabs=getFunction('updateContextTabs');
assert.match(contextTabs,/kind==='video'\)show=\['transform','color','mask','effects','anim','time','3d','shadow','audio'\]\.includes\(t\)/,'video clips expose the Audio inspector tab');
assert.match(contextTabs,/kind==='video'\?\['transform','color','mask','effects','anim','time','3d','shadow','audio'\]/,'video clips enable the Audio inspector panel');
const ctx=vm.createContext({String,Array});
vm.runInContext(`globalThis.normalizeWorkspaceDockOrder=${getFunction('normalizeWorkspaceDockOrder')};globalThis.frameEffectFolder=${getFunction('frameEffectFolder')};`,ctx);
assert.deepEqual(Array.from(ctx.normalizeWorkspaceDockOrder(['inspector','inspector','library','unknown'])),['inspector','library','viewer']);
assert.equal(ctx.frameEffectFolder({category:'Blur · Gaussian'}),'Blur & Distortion');
assert.equal(ctx.frameEffectFolder({category:'Glow · Bloom'}),'Light & Glow');
assert.equal(ctx.frameEffectFolder({category:'Color & Adjustment'}),'Color & Correction');
assert.equal(ctx.frameEffectFolder({category:'Texture'}),'Texture & Style');
assert.equal(ctx.frameEffectFolder({category:'Camera'}),'Motion & Camera');
new vm.Script(renderer,{filename:'renderer-inline.js'});
console.log('FRAME Studio 2.4.44 playhead/audio/workspace UI: OK');
