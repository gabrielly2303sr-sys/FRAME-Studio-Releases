'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const exporter = fs.readFileSync(path.join(root, 'media-export.cjs'), 'utf8');
const main = fs.readFileSync(path.join(root, 'main.cjs'), 'utf8');
assert.equal(pkg.version, '2.4.39');
assert.doesNotMatch(html, /community\.js|community-config\.js|supabase\.co|data-community-tab/i, 'Community and Supabase runtime are completely removed');
assert.ok(!pkg.build.files.some(file => /community/i.test(file)), 'Community is excluded from packaged runtime');
assert.match(html, /@keyframes frameAccentShift/);
assert.match(html, /accent-gradient-active \.transport \.play/);
assert.doesNotMatch(html, /if\(camera3d\.enabled\)draw3DGrid\(\)/, 'editor grid is not drawn into camera composition');
assert.match(html, /id="voiceeffect"/);
assert.match(html, /voiceEffect:\['none','telephone','radio','echo','robot'\]/);
assert.match(exporter, /function voiceEffectFilters\(effect\)/);
for (const effect of ['telephone', 'radio', 'echo', 'robot']) assert.match(exporter, new RegExp(`case '${effect}'`));
assert.match(main, /voiceEffect: \['none', 'telephone', 'radio', 'echo', 'robot'\]/);
assert.match(exporter, /hardwareEncoding: usedEncoder !== 'libx264'/);
assert.match(exporter, /'-c:v', 'libx264'/, 'CPU software fallback remains available');
const renderer = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][0]?.[1] || '';
new vm.Script(renderer, { filename: 'renderer-inline.js' });
console.log('FRAME Studio 2.4.38 regression checks: OK');
