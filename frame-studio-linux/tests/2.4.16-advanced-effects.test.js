'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const main = fs.readFileSync(path.join(root, 'main.cjs'), 'utf8');
const preload = fs.readFileSync(path.join(root, 'preload.cjs'), 'utf8');
const workflow = fs.readFileSync(path.join(root, '..', '.github', 'workflows', 'release.yml'), 'utf8');
assert.equal(pkg.version, '2.4.27');
assert.equal(pkg.devDependencies['electron-builder'], '25.1.8');
assert.match(html, /id="effectSearch"/);
assert.match(html, /data-effect-mode="favorites"/);
assert.match(html, /data-effect-mode="applied"/);
assert.match(html, /id="cameraPreviewCanvas"/);
assert.match(html, /function drawCameraPreviewPip\(/);
assert.match(html, /function cameraMoveTick\(/);
assert.match(html, /function applyInnerGlowToTexture\(/);
assert.match(html, /function applyTurbulentDisplaceEffect\(/);
assert.match(html, /function applyCrumpledPaperEffect\(/);
assert.match(main, /function enumerateSystemFonts\(\)/);
assert.match(preload, /listSystemFonts/);
assert.match(workflow, /npm run build:win:installer/);
assert.match(workflow, /npm run build:linux/);
assert.match(workflow, /latest-linux\.yml/);
assert.doesNotMatch(workflow, /npx electron-builder/);
assert.doesNotMatch(html, /<input[^>]+id="files"[^>]+accept="[^"]*\.glb/);
assert.doesNotMatch(html, /frame-model-runtime\.bundle\.js/);

assert.match(html, /down=norm\(cross\(forward,right\)\)/, 'scene projection should map world +Y upward instead of mirroring vertically');
assert.match(html, /scroll\.scrollTo\(\{left:clamp\(x-scroll.clientWidth\*\.5/, 'keyframe navigation should scroll the target into view');
assert.match(html, /Keyframe found:/, 'keyframe navigation reports its target');
const sceneStart = html.indexOf('function sceneViewState(');
const sceneEnd = html.indexOf('function sceneLayerWorldPoint(', sceneStart);
assert.ok(sceneStart >= 0 && sceneEnd > sceneStart, 'scene projection functions are present');
const sceneApi = vm.runInNewContext(`(()=>{const clamp=(n,a,b)=>Math.max(a,Math.min(b,n));const canvas={width:640,height:360};const camera3d={editorView:{orbitYaw:0,orbitPitch:0,distance:1000,pivotX:0,pivotY:0,pivotZ:0}};${html.slice(sceneStart,sceneEnd)};return {sceneCameraBasis,sceneProjectPoint};})()`, { Math, Number });
const sceneBasis = sceneApi.sceneCameraBasis({ orbitYaw: 0, orbitPitch: 0, distance: 1000, pivotX: 0, pivotY: 0, pivotZ: 0 });
const sceneOrigin = sceneApi.sceneProjectPoint({ x: 0, y: 0, z: 0 }, sceneBasis);
const sceneAbove = sceneApi.sceneProjectPoint({ x: 0, y: 100, z: 0 }, sceneBasis);
assert.ok(sceneAbove.y < sceneOrigin.y, 'world +Y should project upward on screen');

console.log('FRAME Studio 2.4.17 advanced-effects checks: OK');
