'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const gifDecoderSource = fs.readFileSync(path.join(root, 'gif-decoder.js'), 'utf8');
const renderer = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][0]?.[1] || '';
assert.equal(pkg.version, '2.4.35');
assert.equal(pkg.devDependencies['electron-builder'], '25.1.8');
assert.ok(pkg.dependencies['electron-updater']);
assert.doesNotMatch(html.match(/<input[^>]+id="files"[^>]*>/)?.[0] || '', /\.glb|\.gltf|\.obj/);
assert.doesNotMatch(html, /frame-model-runtime\.bundle\.js/);
assert.match(html, /<script src="\.\/gif-decoder\.js"><\/script>/);
assert.match(html, /function decodeGifAsset\(/);
assert.match(html, /function gifFrameIndex\(/);
assert.match(html, /function applyPixelateEffect\(/);
assert.match(html, /function applyDirectionalBlurEffect\(/);
assert.match(html, /function applyTurbulentDisplaceEffect\(/);
assert.match(html, /function applyCrumpledPaperEffect\(/);
assert.match(html, /function applyInnerGlowToTexture\(target,source,pad,bw,bh,amount,radius,scale=1\)/);
for (const prop of ['edgeBlur','innerGlow','pixelateBlur','directionalBlur','turbulentDisplace','crumpledPaper']) assert.match(html, new RegExp(`data-prop="${prop}"`));
for (const category of ['Blur · Gaussian','Blur · Directional','Blur · Edge','Blur · Pixelate','Glow · Bloom','Glow · Inner','Distortion','Texture']) assert.ok(html.includes(category), `effect category ${category}`);
for (const mode of ['overshoot','bounce','elastic','steps']) assert.ok(html.includes(`mode:'${mode}'`), `easing mode ${mode}`);
assert.match(html, /curveStepCount/);
assert.match(html, /effect-target-highlight/);
assert.match(html, /sceneProjectPoint/);
assert.match(gifDecoderSource, /frames\.length \+ 1\) \* width \* height > 40000000/);
assert.equal(pkg.dependencies.three, undefined);
assert.equal(pkg.devDependencies.esbuild, undefined);
const decoder = require(path.join(root, 'gif-decoder.js'));
const fixture = fs.readFileSync(path.join(__dirname, 'fixtures', 'animated-two-frame.gif'));
const decoded = decoder.decode(fixture);
assert.equal(decoded.width, 4);
assert.equal(decoded.height, 4);
assert.equal(decoded.frames.length, 2);
assert.equal(decoded.duration, 300);
assert.deepEqual(Array.from(decoded.frames[0].data.slice(0,4)), [255,0,0,255]);
assert.deepEqual(Array.from(decoded.frames[1].data.slice(0,4)), [0,0,255,255]);
const start = renderer.indexOf('function bezierCoord(');
const end = renderer.indexOf('function baseScale(', start);
assert.ok(start >= 0 && end > start, 'easing evaluators are defined');
const easingApi = vm.runInNewContext(`(()=>{ const clamp=(n,a,b)=>Math.max(a,Math.min(b,n)); ${renderer.slice(start,end)}; return {easeValue,bezierEase}; })()`, { Math, Number });
const ease = easingApi.easeValue;
assert.ok(ease(.8,{mode:'overshoot',x1:.25,y1:.1,x2:.25,y2:1}) > 1, 'overshoot should exceed the final value before settling');
assert.notEqual(ease(.72,{mode:'bounce'}), .72, 'bounce is not linear');
assert.notEqual(ease(.42,{mode:'elastic'}), .42, 'elastic is not linear');
assert.equal(ease(.49,{mode:'steps',steps:4,stepPosition:'end'}), .25);
assert.equal(ease(.51,{mode:'steps',steps:4,stepPosition:'start'}), .75);
console.log('FRAME Studio 2.4.16 GIF/effects/easing regression checks: OK');
