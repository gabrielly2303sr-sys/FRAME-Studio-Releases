'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
assert.equal(packageJson.version, '2.4.41');
assert.match(html, /<div class="toast" id="toast" role="status" aria-live="polite"><\/div>/, 'toast host exists before renderer initialization');
assert.match(html, /function message\(t\)\{[^}]*if\(!el\)/, 'message handles a missing toast element without throwing');
assert.match(html, /function setStatus\(t\)\{const el=\$\('\#status'\);if\(el\)/, 'status updates are guarded');
assert.match(html, /function requestTextInput\(/, 'Electron-safe in-app text input dialog exists');
assert.match(html, /async function groupSelectedClips\(/, 'group creation awaits in-app text entry');
assert.match(html, /await requestTextInput\(\{title:'Criar grupo'/, 'group creation no longer calls the unsupported browser prompt');
assert.doesNotMatch(html, /\bprompt\s*\(/, 'no window.prompt calls remain in the renderer');
assert.match(html, /const publishExportProfile=\(status=profileStatus,extra=\{\}\)=>/, 'export profile publisher exists');
assert.match(html, /publishExportProfile\('starting'\)/, 'export diagnostics are available before rendering starts');
assert.match(html, /publishExportProfile\(wasCancelled\?'cancelled':'failed'/, 'failed and cancelled exports preserve diagnostics');
assert.match(html, /window\.lastExportProfile=profileSummary/, 'profile remains available from DevTools');
console.log('FRAME Studio Electron toast, text-dialog and export-profile regressions: OK');
