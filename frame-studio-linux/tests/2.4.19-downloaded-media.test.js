'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const main = fs.readFileSync(path.join(root, 'main.cjs'), 'utf8');
const preload = fs.readFileSync(path.join(root, 'preload.cjs'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const workflow = fs.readFileSync(path.join(root, '..', '.github', 'workflows', 'release.yml'), 'utf8');

assert.equal(pkg.version, '2.4.39');
assert.match(pkg.build.win.extraResources.map(x => `${x.from}=>${x.to}`).join('\n'), /vendor\/win=>downloader/);
assert.match(pkg.build.linux.extraResources.map(x => `${x.from}=>${x.to}`).join('\n'), /vendor\/linux=>downloader/);
assert.match(main, /function downloadedMediaRoot\(\)\s*\{\s*return path\.join\(app\.getPath\('userData'\), 'Media Library', 'Downloaded Media'\)/);
assert.match(main, /function normalizeLibraryRelative\(/);
assert.match(main, /pieces\.some\(piece => piece === '\.' \|\| piece === '\.\.'/, 'relative library paths reject traversal segments');
assert.match(main, /frame:downloaded-media-list/);
assert.match(main, /frame:downloaded-media-create-folder/);
assert.match(main, /frame:downloaded-media-resolve/);
assert.match(main, /frame:downloaded-media-open-folder/);
assert.match(main, /function bundledToolPath\(/);
assert.match(fs.readFileSync(path.join(root, 'media-tools.cjs'), 'utf8'), /pathApi\.join\(resourcesPath, 'downloader', filename\)/);
assert.match(main, /resourcesPath: process\.resourcesPath/);
assert.match(main, /function configureBundledMediaTools\(/);
assert.match(main, /'--paths', `home:\$\{targetDir\}`/);
assert.match(main, /'--paths', `temp:\$\{tempDir\}`/);
assert.match(main, /'after_move:FRAME_OUTPUT:%\(filepath\)s'/);
assert.doesNotMatch(main.slice(main.indexOf('async function runYoutubeDownload'), main.indexOf('\nfunction createWindow()')), /showSaveDialog/, 'downloads should save directly into the persistent library');
assert.match(preload, /listDownloadedMedia:/);
assert.match(preload, /createDownloadedMediaFolder:/);
assert.match(preload, /resolveDownloadedMedia:/);
assert.match(preload, /openDownloadedMediaFolder:/);
assert.match(html, /data-library-view="downloaded"/);
assert.match(html, /id="downloadedMediaPane"/);
assert.match(html, /id="ytLibraryFolder"/);
assert.match(html, /application\/x-frame-library-media/);
assert.match(html, /function importDownloadedMediaToBin\(/);
assert.match(html, /const timelineDrop=async\(e\)=>/);
assert.match(html, /id="downloadFolderCreate"/);
assert.match(html, /id="downloadFolderUp"/);
assert.match(html, /id="downloadFolderOpen"/);
assert.match(workflow, /yt-dlp\/yt-dlp\/releases\/latest\/download\/yt-dlp\.exe/);
assert.match(workflow, /yt-dlp\/yt-dlp\/releases\/latest\/download\/yt-dlp/);
assert.match(workflow, /vendor\\win/);
assert.match(workflow, /vendor\/linux/);
assert.match(workflow, /ffmpeg-release-essentials\.zip/);
assert.match(workflow, /ffmpeg-release-amd64-static\.tar\.xz/);
console.log('FRAME Studio 2.4.23 downloaded-media library and bundled tools checks: OK');
