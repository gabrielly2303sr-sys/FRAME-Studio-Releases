const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const main = fs.readFileSync(path.join(root, 'main.cjs'), 'utf8');
const preload = fs.readFileSync(path.join(root, 'preload.cjs'), 'utf8');
const installer = fs.readFileSync(path.join(root, 'install-linux.sh'), 'utf8');
const readme = fs.readFileSync(path.join(root, 'README.md'), 'utf8');
assert.equal(pkg.version, '2.4.25');
assert.equal(pkg.build.publish[0].provider, 'github');
assert.equal(pkg.build.publish[0].owner, 'gabrielly2303sr-sys');
assert.equal(pkg.build.publish[0].repo, 'FRAME-Studio-Releases');
assert.ok(pkg.dependencies['electron-updater']);
assert.match(main, /function supportsAutomaticUpdates\(\)/);
assert.match(main, /PORTABLE_EXECUTABLE_DIR/);
assert.match(main, /process\.env\.APPIMAGE/);
assert.match(main, /autoUpdater\.checkForUpdates\(\)/);
assert.match(main, /autoUpdater\.downloadUpdate\(\)/);
assert.match(main, /autoUpdater\.quitAndInstall\(false, true\)/);
assert.match(main, /latest|updater/i);
assert.match(preload, /onAutoUpdateProgress/);
assert.match(installer, /VERSION=/);
assert.doesNotMatch(installer, /FRAME Studio 2\.4\.11 installed/);
assert.match(readme, /latest\.yml/);
assert.match(readme, /latest-linux\.yml/);
console.log('FRAME Studio auto-update configuration tests: OK');
