const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const main = fs.readFileSync(path.join(root, 'main.cjs'), 'utf8');
const preload = fs.readFileSync(path.join(root, 'preload.cjs'), 'utf8');
const installer = fs.readFileSync(path.join(root, 'install-linux.sh'), 'utf8');
const readme = fs.readFileSync(path.join(root, 'README.md'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
assert.equal(pkg.version, '2.4.39');
assert.equal(pkg.build.publish[0].provider, 'github');
assert.equal(pkg.build.publish[0].owner, 'gabrielly2303sr-sys');
assert.equal(pkg.build.publish[0].repo, 'FRAME-Studio-Releases');
assert.ok(pkg.dependencies['electron-updater']);
assert.match(main, /function supportsAutomaticUpdates\(\)/);
assert.match(main, /PORTABLE_EXECUTABLE_DIR/);
assert.match(main, /process\.env\.APPIMAGE/);
assert.match(main, /autoUpdater\.checkForUpdates\(\)/);
assert.match(main, /const scheduleRetry = \(\) =>/);
assert.match(main, /retryDelayMs = Math\.min\(retryDelayMs \* 2, 15 \* 60 \* 1000\)/);
assert.match(main, /checkInProgress/);
assert.ok(pkg.build.files.includes('media-range.cjs'), 'range responder must be bundled into packaged apps');
assert.match(main, /autoUpdater\.downloadUpdate\(\)/);
assert.match(main, /autoUpdater\.quitAndInstall\(false, true\)/);
assert.match(main, /latest|updater/i);
assert.match(preload, /onAutoUpdateProgress/);
assert.match(html, /id="updateDownloadPanel"/, 'visible updater progress panel must exist');
assert.match(html, /id="updateDownloadBar"/, 'visible updater progress bar must exist');
assert.match(html, /id="updateDownloadPercent"/, 'progress percentage must be visible');
assert.match(html, /if\(stage==='downloading'\)/, 'download events must update the progress panel');
assert.match(html, /progress\.setAttribute\('aria-valuenow'/, 'progress bar must expose accessible progress');
assert.match(html, /Baixando FRAME Studio \$\{target\}/, 'progress panel must identify the downloaded version');
assert.match(installer, /VERSION=/);
assert.match(installer, /media-range\.cjs/);
assert.match(installer, /media-tools\.cjs/);
assert.match(installer, /video-preview-seek\.js/);
assert.doesNotMatch(installer, /FRAME Studio 2\.4\.11 installed/);
assert.match(readme, /latest\.yml/);
assert.match(readme, /latest-linux\.yml/);
console.log('FRAME Studio auto-update configuration tests: OK');
