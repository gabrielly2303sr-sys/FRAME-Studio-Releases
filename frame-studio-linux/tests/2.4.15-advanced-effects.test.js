'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const runtime = fs.readFileSync(path.join(root, 'model-runtime.js'), 'utf8');
const workflow = fs.readFileSync(path.join(root, '..', '.github', 'workflows', 'release.yml'), 'utf8');
const readme = fs.readFileSync(path.join(root, '..', 'README-SOURCE-KIT.md'), 'utf8');
assert.equal(pkg.version, '2.4.15');
assert.equal(pkg.devDependencies['electron-builder'], '25.1.8');
assert.ok(pkg.dependencies.three, 'Three.js runtime dependency must be present');
assert.ok(pkg.devDependencies.esbuild, 'esbuild must be present to package the GLB runtime');
assert.match(pkg.scripts.prepare, /build:vendor/);
assert.match(pkg.build.files.join(' '), /frame-model-runtime\.bundle\.js/);
assert.equal(pkg.build.linux.desktop, undefined, 'obsolete linux.desktop property must not break electron-builder schema validation');
assert.match(html, /id="effectSearch"/);
assert.match(html, /data-effect-mode="favorites"/);
assert.match(html, /data-effect-mode="applied"/);
for (const prop of ['edgeBlur', 'innerGlow', 'pixelateBlur', 'directionalBlur']) assert.match(html, new RegExp(`data-prop="${prop}"`));
assert.match(html, /function applyEdgeBlurToTexture\(/);
assert.match(html, /function applyInnerGlowToTexture\(/);
assert.match(html, /function applyPixelateEffect\(/);
assert.match(html, /function applyDirectionalBlurEffect\(/);
assert.match(html, /function frameEffectIsEnabled\(/);
assert.match(html, /id="cameraPreviewCanvas"/);
assert.match(html, /function drawCameraPreviewPip\(/);
assert.match(html, /function cameraRenderPoseAtTime\(/);
assert.match(html, /function cameraMoveTick\(/);
assert.match(html, /\.glb,.gltf/);
assert.match(html, /prepareModelSource\(/);
assert.match(html, /0x46546c67/, 'GLB header is parsed when external GLB texture dependencies must be inlined');
assert.match(html, /entry\.uri=await resolveUri\(entry\.uri\)/, 'external glTF resources are embedded for portability');
assert.match(html, /modelSourceText:a\.kind==='model3d'\?a\.modelSourceText\|\|null:null/, 'model source data persists with the project');
assert.match(html, /cameraPreviewDrawing=false;drawSceneEditorViewport\(\)/, 'camera preview returns to the scene editor without resetting blur history each frame');
assert.match(html, /listSystemFonts/);
assert.match(html, /async function getMissingProjectFonts/);
assert.match(html, /notifyMissingProjectFonts/);
assert.match(html, /fallback font will be used/i);
assert.match(runtime, /GLTFLoader/);
assert.match(runtime, /preserveDrawingBuffer\s*:\s*true/);
assert.match(runtime, /AnimationMixer/);
assert.match(workflow, /npm run build:win:installer/);
assert.match(workflow, /npm run build:linux/);
assert.match(fs.readFileSync(path.join(root, 'install-linux.sh'), 'utf8'), /build:vendor/, 'source install prepares the Three.js model runtime when absent');
assert.match(fs.readFileSync(path.join(root, 'install-linux.sh'), 'utf8'), /frame-model-runtime\.bundle\.js/, 'source install copies the generated model runtime');
assert.doesNotMatch(workflow, /npx electron-builder/);
assert.match(readme, /not yet a native mesh/i);
assert.match(readme, /latest-linux\.yml/);
console.log('FRAME Studio 2.4.15 advanced effects checks: OK');
