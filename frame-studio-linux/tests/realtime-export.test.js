'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const main = fs.readFileSync(path.join(root, 'main.cjs'), 'utf8');
const preload = fs.readFileSync(path.join(root, 'preload.cjs'), 'utf8');
const media = fs.readFileSync(path.join(root, 'media-export.cjs'), 'utf8');
const renderer = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][0]?.[1] || '';

assert.equal(pkg.version, '2.4.44');
assert.match(html, /<title>FRAME Studio 2\.4\.44<\/title>/);
assert.match(html, /id="previewfullscreen"/);
assert.match(html, /id="exportformat"/);
assert.match(html, /id="exportmode"/);
assert.match(renderer, /function exportProjectFrameAccurate\(/, 'the deterministic renderer remains available as a fallback');
assert.match(renderer, /async function exportProject\(/, 'the main export action uses the realtime path');
assert.match(renderer, /previewCanvas\.captureStream\(fps\)/);
assert.match(renderer, /new MediaRecorder\(combinedStream/);
assert.match(renderer, /writeRealtimeExportChunk\(sessionId,thisIndex,buffer\)/);
assert.match(renderer, /console\.error\('FRAME Studio export failed:'/);
assert.match(renderer, /console\.error\('FRAME Studio deterministic export failed:'/);
assert.match(main, /ipcMain\.handle\('frame:begin-realtime-export'/);
assert.match(main, /ipcMain\.handle\('frame:write-realtime-export-chunk'/);
assert.match(main, /ipcMain\.handle\('frame:finish-realtime-export'/);
assert.match(main, /ipcMain\.handle\('frame:cancel-realtime-export'/);
assert.match(preload, /beginRealtimeExport:/);
assert.match(preload, /writeRealtimeExportChunk:/);
assert.match(preload, /finishRealtimeExport:/);
assert.match(preload, /cancelRealtimeExport:/);
assert.match(media, /async function copyValidatedWebm\(/);
assert.match(media, /async function transcodeWebmToFormat\(/);
assert.match(media, /module\.exports = \{[^}]*transcodeWebmToFormat[^}]*copyValidatedWebm/);
assert.match(media, /'libx264'/);
assert.match(media, /'aac'/);
console.log('FRAME Studio 2.4.44 realtime export/fullscreen regression checks: OK');
