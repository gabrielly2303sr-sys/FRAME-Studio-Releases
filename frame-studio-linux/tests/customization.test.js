const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const core = require('../customization.js');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const main = fs.readFileSync(path.join(root, 'main.cjs'), 'utf8');
const preload = fs.readFileSync(path.join(root, 'preload.cjs'), 'utf8');
const installer = fs.readFileSync(path.join(root, 'install-linux.sh'), 'utf8');
assert.equal(core.normalizeSettings({}).blur, 8);
assert.equal(core.normalizeSettings({}).overlay, 48);
assert.equal(core.normalizeSettings({}).brightness, 85);
assert.equal(core.normalizeSettings({}).uiOpacity, 92);
assert.equal(core.normalizeSettings({ language: 'en-US', accent: '#8ab4ff', blur: 100, overlay: -3 }).language, 'en-US');
assert.equal(core.normalizeSettings({ blur: 100 }).blur, 32);
assert.equal(core.normalizeSettings({ overlay: -3 }).overlay, 0);
assert.equal(core.normalizeSettings({ bgX: 200, uiOpacity: 1 }).bgX, 100);
assert.equal(core.normalizeSettings({ uiOpacity: 1 }).uiOpacity, 50);
assert.equal(core.validHex('not-a-color', '#b5f36c'), '#b5f36c');
assert.equal(core.normalizeSettings({ accentMode: 'gradient' }).accentMode, 'gradient');
assert.deepEqual(core.normalizeAccentGradient({ angle: 999, colors: ['#ff0000', 'invalid', '#0000ff'] }), { angle: 360, colors: ['#ff0000', '#a78bfa', '#0000ff'] });
assert.match(core.accentGradientCss({ angle: 40, colors: ['#ff0000', '#00ff00', '#0000ff'] }), /^linear-gradient\(40deg/);
assert.equal(core.accentTextColor('#f0f0f4'), '#141418');
assert.equal(core.accentTextColor('#24243a'), '#f5f5f7');
assert.equal(core.TRANSLATIONS['Personalização do FRAME Studio'], 'FRAME Studio customization');
assert.match(html, /id="customizationdialog"/);
assert.match(html, /id="customAccentGradientControls"/);
assert.match(html, /id="customAccentGradient1"/);
assert.match(html, /id="customAccentGradientAngle"/);
assert.match(html, /id="customBackgroundVideo"/);
assert.match(html, /id="customBlur"/);
assert.match(html, /id="customReduceMotion"/);
assert.match(html, /<script src="\.\/customization\.js"><\/script>/);
assert.match(preload, /selectCustomizationBackground: \(\) => ipcRenderer\.invoke\('frame:select-custom-background'\)/);
assert.match(main, /ipcMain\.handle\('frame:select-custom-background'/);
assert.match(main, /assertTrustedSender\(event\)/);
assert.match(installer, /customization\.js/);
console.log('FRAME Studio 2.4.16 customization tests: OK');
