create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username ~ '^[A-Za-z0-9_.-]{3,24}$'),
  display_name text not null check (char_length(display_name) between 1 and 40),
  bio text not null default '' check (char_length(bio) <= 160),
  pronouns text not null default '' check (char_length(pronouns) <= 40),
  avatar_url text,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists profiles_username_lower_unique on public.profiles (lower(username));
create index if not exists profiles_created_at_idx on public.profiles (created_at desc);
create index if not exists profiles_last_seen_at_idx on public.profiles (last_seen_at desc);
alter table public.profiles enable row level security;

drop policy if exists "Public can view community profiles" on public.profiles;
create policy "Public can view community profiles" on public.profiles
  for select to anon, authenticated using (true);
drop policy if exists "Users can create their own profile" on public.profiles;
create policy "Users can create their own profile" on public.profiles
  for insert to authenticated with check (auth.uid() = id);
drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile" on public.profiles
  for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
grant select on public.profiles to anon, authenticated;
grant insert, update on public.profiles to authenticated;

create table if not exists public.friend_requests (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'accepted', 'declined')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint friend_requests_no_self check (sender_id <> receiver_id),
  constraint friend_requests_direction_unique unique (sender_id, receiver_id)
);
create index if not exists friend_requests_receiver_status_idx on public.friend_requests (receiver_id, status, created_at desc);
create index if not exists friend_requests_sender_status_idx on public.friend_requests (sender_id, status, created_at desc);
alter table public.friend_requests enable row level security;
drop policy if exists "Users can view their own friend requests" on public.friend_requests;
create policy "Users can view their own friend requests" on public.friend_requests
  for select to authenticated using (auth.uid() = sender_id or auth.uid() = receiver_id);
grant select on public.friend_requests to authenticated;

create table if not exists public.user_blocks (
  blocker_id uuid not null references public.profiles(id) on delete cascade,
  blocked_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  constraint user_blocks_no_self check (blocker_id <> blocked_id)
);
alter table public.user_blocks enable row level security;
drop policy if exists "Users can see blocks involving their account" on public.user_blocks;
create policy "Users can see blocks involving their account" on public.user_blocks
  for select to authenticated using (auth.uid() = blocker_id or auth.uid() = blocked_id);
grant select on public.user_blocks to authenticated;

create table if not exists public.profile_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references public.profiles(id) on delete cascade,
  reported_id uuid not null references public.profiles(id) on delete cascade,
  reason text not null check (char_length(reason) between 1 and 80),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  constraint profile_reports_no_self check (reporter_id <> reported_id)
);
create index if not exists profile_reports_created_at_idx on public.profile_reports (created_at desc);
alter table public.profile_reports enable row level security;
drop policy if exists "Users can submit their own profile reports" on public.profile_reports;
create policy "Users can submit their own profile reports" on public.profile_reports
  for insert to authenticated with check (auth.uid() = reporter_id and reporter_id <> reported_id);
drop policy if exists "Users can view reports they submitted" on public.profile_reports;
create policy "Users can view reports they submitted" on public.profile_reports
  for select to authenticated using (auth.uid() = reporter_id);
grant insert, select on public.profile_reports to authenticated;

create or replace function public.send_friend_request(target_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
declare current_id uuid := auth.uid();
begin
  if current_id is null then raise exception 'You must sign in first'; end if;
  if target_user_id is null or target_user_id = current_id then raise exception 'Invalid friend target'; end if;
  if not exists (select 1 from public.profiles where id = target_user_id) then raise exception 'Profile not found'; end if;
  if exists (select 1 from public.user_blocks b where (b.blocker_id = current_id and b.blocked_id = target_user_id) or (b.blocker_id = target_user_id and b.blocked_id = current_id)) then
    raise exception 'Friend requests are not available for this profile';
  end if;
  if exists (select 1 from public.friend_requests f where f.status = 'accepted' and ((f.sender_id = current_id and f.receiver_id = target_user_id) or (f.sender_id = target_user_id and f.receiver_id = current_id))) then
    raise exception 'You are already friends';
  end if;
  if exists (select 1 from public.friend_requests f where f.sender_id = target_user_id and f.receiver_id = current_id and f.status = 'pending') then
    update public.friend_requests set status = 'accepted', updated_at = now() where sender_id = target_user_id and receiver_id = current_id and status = 'pending';
    return;
  end if;
  insert into public.friend_requests (sender_id, receiver_id, status) values (current_id, target_user_id, 'pending')
  on conflict (sender_id, receiver_id) do update set status = 'pending', created_at = now(), updated_at = now()
    where public.friend_requests.status = 'declined';
  if not found then raise exception 'A request already exists'; end if;
end;
$$;

create or replace function public.respond_friend_request(p_request_id bigint, p_decision text)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
declare changed integer;
begin
  if auth.uid() is null then raise exception 'You must sign in first'; end if;
  if p_decision not in ('accept', 'decline') then raise exception 'Invalid decision'; end if;
  update public.friend_requests
    set status = case when p_decision = 'accept' then 'accepted' else 'declined' end,
        updated_at = now()
    where id = p_request_id and receiver_id = auth.uid() and status = 'pending'
      and not exists (select 1 from public.user_blocks b where (b.blocker_id = sender_id and b.blocked_id = receiver_id) or (b.blocker_id = receiver_id and b.blocked_id = sender_id));
  get diagnostics changed = row_count;
  if changed = 0 then raise exception 'Request not found, expired, or blocked'; end if;
end;
$$;

create or replace function public.remove_friend(friend_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if auth.uid() is null then raise exception 'You must sign in first'; end if;
  delete from public.friend_requests
    where status = 'accepted'
      and ((sender_id = auth.uid() and receiver_id = friend_user_id) or (sender_id = friend_user_id and receiver_id = auth.uid()));
end;
$$;

create or replace function public.block_user(target_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if auth.uid() is null then raise exception 'You must sign in first'; end if;
  if target_user_id is null or target_user_id = auth.uid() then raise exception 'Invalid profile'; end if;
  if not exists (select 1 from public.profiles where id = target_user_id) then raise exception 'Profile not found'; end if;
  insert into public.user_blocks (blocker_id, blocked_id) values (auth.uid(), target_user_id) on conflict do nothing;
  delete from public.friend_requests
    where (sender_id = auth.uid() and receiver_id = target_user_id) or (sender_id = target_user_id and receiver_id = auth.uid());
end;
$$;

create or replace function public.unblock_user(target_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if auth.uid() is null then raise exception 'You must sign in first'; end if;
  delete from public.user_blocks where blocker_id = auth.uid() and blocked_id = target_user_id;
end;
$$;

revoke all on function public.send_friend_request(uuid) from public;
revoke all on function public.respond_friend_request(bigint, text) from public;
revoke all on function public.remove_friend(uuid) from public;
revoke all on function public.block_user(uuid) from public;
revoke all on function public.unblock_user(uuid) from public;
grant execute on function public.send_friend_request(uuid) to authenticated;
grant execute on function public.respond_friend_request(bigint, text) to authenticated;
grant execute on function public.remove_friend(uuid) to authenticated;
grant execute on function public.block_user(uuid) to authenticated;
grant execute on function public.unblock_user(uuid) to authenticated;

-- Avatar storage is public-read so profile pictures can be displayed; uploads are restricted to the owner's folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('profile-avatars', 'profile-avatars', true, 2097152, array['image/png', 'image/jpeg', 'image/webp', 'image/gif'])
on conflict (id) do update set public = true, file_size_limit = 2097152, allowed_mime_types = excluded.allowed_mime_types;
drop policy if exists "Community avatars are publicly readable" on storage.objects;
create policy "Community avatars are publicly readable" on storage.objects
  for select to anon, authenticated using (bucket_id = 'profile-avatars');
drop policy if exists "Users upload avatars to their own folder" on storage.objects;
create policy "Users upload avatars to their own folder" on storage.objects
  for insert to authenticated with check (bucket_id = 'profile-avatars' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Users update avatars in their own folder" on storage.objects;
create policy "Users update avatars in their own folder" on storage.objects
  for update to authenticated using (bucket_id = 'profile-avatars' and (storage.foldername(name))[1] = auth.uid()::text)
  with check (bucket_id = 'profile-avatars' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Users delete avatars in their own folder" on storage.objects;
create policy "Users delete avatars in their own folder" on storage.objects
  for delete to authenticated using (bucket_id = 'profile-avatars' and (storage.foldername(name))[1] = auth.uid()::text);
